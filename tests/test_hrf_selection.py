def _build_hrf_test_inputs(
    true_hrf_idx: int = 0,
    n_runs: int = 3,
    n_tp_run: int = 60,
    tr: float = 2.0,
    microtime_dt: float = 0.1,
    n_conditions: int = 2,
    n_voxels: int = 20,
    noise_level: float = 0.3,
    seed: int = 42,
):
    """
    Build minimal fMRI-like inputs for testing fit_glm_hrf_library_with_xval.

    Returns (data, onset_matrix, hrf_library, run_starts, n_tp_total, tr).
    data is (n_voxels, n_tp_total).  The first n_voxels//2 have clear signal
    generated by hrf_library[true_hrf_idx]; the rest are pure noise.
    """
    from fastfuncstuff.design.builder import create_onset_matrix_microtime
    from fastfuncstuff.design.matrices import convolve_hrf_microtime

    torch.manual_seed(seed)
    n_tp_total = n_runs * n_tp_run
    run_starts = [i * n_tp_run for i in range(n_runs)]

    # Place 3 events per condition per run, spread across run
    spacing_tr = n_tp_run // (n_conditions * 3 + 1)
    all_onsets: list[list[np.ndarray]] = []
    for cond in range(n_conditions):
        cond_onsets = []
        for _ in range(n_runs):
            base = cond * 3
            event_trs = [base * spacing_tr + k * spacing_tr for k in range(3)]
            cond_onsets.append(np.array([t * tr for t in event_trs], dtype=float))
        all_onsets.append(cond_onsets)

    stim_durations = [0.0] * n_conditions
    onset_matrix = create_onset_matrix_microtime(
        all_onsets, run_starts, tr, n_tp_total, microtime_dt, stim_durations, torch.device("cpu")
    )

    # A small HRF library: 3 distinct HRFs at microtime resolution.
    # HRF 0 (fast): narrow peak at 5s; HRF 1 (canonical): peak at 6s;
    # HRF 2 (slow): peak at 8s.
    n_hrf_bins = int(round(32.0 / microtime_dt))
    t_hrf = np.arange(n_hrf_bins) * microtime_dt
    hrfs = []
    for peak_time in [5.0, 6.0, 8.0]:
        h = np.exp(-0.5 * ((t_hrf - peak_time) / 1.5) ** 2) - 0.35 * np.exp(
            -0.5 * ((t_hrf - (peak_time + 4)) / 3.0) ** 2
        )
        h = h / np.abs(h).max()
        hrfs.append(h)
    hrf_library = torch.from_numpy(np.stack(hrfs).astype(np.float32))  # (3, n_hrf_bins)

    # Simulate data: first half of voxels have signal from true_hrf
    true_hrf = hrf_library[true_hrf_idx]
    design_out = convolve_hrf_microtime(
        onset_matrix,
        true_hrf,
        n_tp_total,
        tr=tr,
        microtime_dt=microtime_dt,
        device=torch.device("cpu"),
    )
    assert isinstance(design_out, torch.Tensor), "Expected tensor from convolve_hrf_microtime"

    betas_high = torch.randn(n_voxels // 2, n_conditions) * 3.0
    signal = betas_high @ design_out.T  # (n_voxels//2, n_tp_total)
    noise_high = torch.randn(n_voxels // 2, n_tp_total) * noise_level
    noise_low = torch.randn(n_voxels - n_voxels // 2, n_tp_total) * 1.0

    data = torch.cat([signal + noise_high, noise_low], dim=0)  # (n_voxels, n_tp_total)

    return data, onset_matrix, hrf_library, run_starts, n_tp_total, tr


def test_condition_level_library_uses_raw_events_not_binary_regions(monkeypatch):
    """Library selection must not reconstruct trials from merged duration boxes."""
    from fastfuncstuff.design.hrf_selection import fit_glm_hrf_library_with_xval
    from fastfuncstuff.design.matrices import build_event_design_microtime

    tr = 1.0
    dt = 0.5
    run_starts = [0, 20]
    event_onsets = [[np.array([2.0, 5.0]), np.array([2.0, 4.0])]]
    durations = [3.0]
    library = torch.tensor(
        [
            [0.0, 0.4, 1.0, 0.5, 0.1, 0.0],
            [0.0, 0.2, 0.7, 1.0, 0.6, 0.2],
        ]
    )
    truth = build_event_design_microtime(
        event_onsets,
        durations,
        library[1],
        [20, 20],
        tr=tr,
        microtime_dt=dt,
        device=torch.device("cpu"),
    )
    assert isinstance(truth, torch.Tensor)
    data = truth.T.repeat(4, 1)
    sampled_placeholder = torch.zeros(80, 1)

    def _legacy_path_is_a_bug(*args, **kwargs):
        raise AssertionError("raw events unexpectedly fell back to binary-region convolution")

    monkeypatch.setattr(
        "fastfuncstuff.design.hrf_selection.convolve_hrf_microtime", _legacy_path_is_a_bug
    )
    result = fit_glm_hrf_library_with_xval(
        data=data,
        onsets=sampled_placeholder,
        hrf_library=library,
        tr=tr,
        run_starts=run_starts,
        stim_durations=durations,
        microtime_dt=dt,
        polort=-1,
        select_mode="full",
        skip_final_fit=True,
        event_onsets=event_onsets,
        device=torch.device("cpu"),
        verbose=False,
    )
    assert result.hrf_index.shape == (4,)


