    def test_per_voxel_hrf_selection_distinguishes_groups(self, device):
        """
        When two groups of voxels have signal generated by different HRFs
        (HRF 0 vs HRF 2), the majority of each group selects its own HRF.
        """
        from fastfuncstuff.design.builder import create_onset_matrix_microtime
        from fastfuncstuff.design.matrices import convolve_hrf_microtime

        torch.manual_seed(7)
        n_runs, n_tp_run, tr, microtime_dt = 4, 80, 2.0, 0.1
        n_conditions, n_voxels_per_group = 2, 15

        n_tp_total = n_runs * n_tp_run
        run_starts = [i * n_tp_run for i in range(n_runs)]

        spacing_tr = 8
        all_onsets: list[list[np.ndarray]] = []
        for cond in range(n_conditions):
            cond_onsets = []
            for _ in range(n_runs):
                event_trs = [cond * spacing_tr + k * (2 * spacing_tr) for k in range(3)]
                cond_onsets.append(np.array([t * tr for t in event_trs], dtype=float))
            all_onsets.append(cond_onsets)

        stim_durations = [0.0] * n_conditions
        onset_matrix = create_onset_matrix_microtime(
            all_onsets,
            run_starts,
            tr,
            n_tp_total,
            microtime_dt,
            stim_durations,
            torch.device("cpu"),
        )

        n_hrf_bins = int(round(32.0 / microtime_dt))
        t_hrf = np.arange(n_hrf_bins) * microtime_dt
        hrfs = []
        for peak_time in [5.0, 6.0, 8.0]:
            h = np.exp(-0.5 * ((t_hrf - peak_time) / 1.5) ** 2) - 0.35 * np.exp(
                -0.5 * ((t_hrf - (peak_time + 4)) / 3.0) ** 2
            )
            h = h / np.abs(h).max()
            hrfs.append(h)
        hrf_library = torch.from_numpy(np.stack(hrfs).astype(np.float32))

        data_parts = []
        for hrf_idx in [0, 2]:
            d_out = convolve_hrf_microtime(
                onset_matrix,
                hrf_library[hrf_idx],
                n_tp_total,
                tr=tr,
                microtime_dt=microtime_dt,
                device=torch.device("cpu"),
            )
            assert isinstance(d_out, torch.Tensor)
            betas = torch.ones(n_voxels_per_group, n_conditions) * 5.0
            signal = betas @ d_out.T
            noise = torch.randn(n_voxels_per_group, n_tp_total) * 0.1
            data_parts.append(signal + noise)

        data = torch.cat(data_parts, dim=0)

        results = fit_glm_hrf_library_with_xval(
            data=data,
            onsets=onset_matrix,
            hrf_library=hrf_library,
            tr=tr,
            run_starts=run_starts,
            polort=1,
            verbose=False,
            device=device,
        )

        group_a_idx = results.hrf_index[:n_voxels_per_group].cpu().numpy()
        group_b_idx = results.hrf_index[n_voxels_per_group:].cpu().numpy()

        frac_a_correct = (group_a_idx == 0).mean()
        frac_b_correct = (group_b_idx == 2).mean()

        assert frac_a_correct >= 0.6, (
            f"Group A (HRF 0) correct fraction too low: {frac_a_correct:.2f}"
        )
        assert frac_b_correct >= 0.6, (
            f"Group B (HRF 2) correct fraction too low: {frac_b_correct:.2f}"
        )

