class TestLoadHrfSelectionForArma:
    def test_round_trip_of_full_payload(self, tmp_path):
        """The function is a thin torch.load wrapper; the contract is that
        it returns the dict that was saved, including tensors and metadata."""
        payload = {
            "hrf_library": torch.randn(5, 30),
            "hrf_index": torch.tensor([0, 1, 2, 0, 1], dtype=torch.int64),
            "hrf_group_indices": {0: [0, 3], 1: [1, 4], 2: [2]},
            "metadata": {"tr": 2.0, "stim_durations": [3.0]},
        }
        f = tmp_path / "hrf_lib.pt"
        torch.save(payload, f)
        loaded = load_hrf_selection_for_arma(str(f))
        torch.testing.assert_close(loaded["hrf_library"], payload["hrf_library"])
        torch.testing.assert_close(loaded["hrf_index"], payload["hrf_index"])
        assert loaded["hrf_group_indices"] == payload["hrf_group_indices"]
        assert loaded["metadata"] == payload["metadata"]
