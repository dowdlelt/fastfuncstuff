class TestWriteAfniXmat:
    def test_basic_header_attrs(self, tmp_path):
        T, n_stim, n_poly_total = 20, 2, 6
        X = np.random.default_rng(0).standard_normal((T, n_stim + n_poly_total)).astype(np.float32)
        out = tmp_path / "design.xmat.1D"
        _write_afni_xmat(
            X,
            str(out),
            n_stim_cols=n_stim,
            condition_labels=["A", "B"],
            run_starts=[0, 10],
            tr=2.0,
            polort=2,
        )
        text = out.read_text()
        assert "<matrix" in text
        assert f'ni_type = "{n_stim + n_poly_total}*double"' in text
        assert f'ni_dimen = "{T}"' in text
        assert 'RowTR = "2.0"' in text
        assert 'RunStart = "0,10"' in text
        assert 'Nstim = "2"' in text

    def test_polort_labels_per_run(self, tmp_path):
        """With polort=p and n_runs runs, labels are r01_poly0..r01_polyp,
        r02_poly0..r02_polyp, etc."""
        T, n_stim = 20, 2
        n_poly_total = 2 * 3  # 2 runs × (polort=2 → 3 polys)
        X = np.zeros((T, n_stim + n_poly_total))
        out = tmp_path / "design.xmat.1D"
        _write_afni_xmat(
            X,
            str(out),
            n_stim_cols=n_stim,
            condition_labels=["A", "B"],
            run_starts=[0, 10],
            tr=2.0,
            polort=2,
        )
        text = out.read_text()
        for r in (1, 2):
            for p in (0, 1, 2):
                assert f"r{r:02d}_poly{p}" in text

    def test_extra_nuisance_labels(self, tmp_path):
        T, n_stim = 20, 1
        n_poly = 2  # 1 run × (polort=1 → 2 polys)
        n_motion = 6
        X = np.zeros((T, n_stim + n_poly + n_motion))
        out = tmp_path / "design.xmat.1D"
        motion_labels = [f"motion_{i}" for i in range(6)]
        _write_afni_xmat(
            X,
            str(out),
            n_stim_cols=n_stim,
            condition_labels=["face"],
            run_starts=[0],
            tr=2.0,
            polort=1,
            extra_nuisance_labels=motion_labels,
        )
        text = out.read_text()
        for ml in motion_labels:
            assert ml in text

    def test_no_condition_labels_falls_back_to_stim_indices(self, tmp_path):
        T = 10
        X = np.zeros((T, 3))  # 2 stim + 1 nuisance
        out = tmp_path / "design.xmat.1D"
        _write_afni_xmat(
            X,
            str(out),
            n_stim_cols=2,
            condition_labels=None,
            run_starts=[0],
            tr=1.0,
            polort=0,
        )
        text = out.read_text()
        assert "stim00" in text
        assert "stim01" in text

    def test_data_rows_match_input_matrix(self, tmp_path):
        T = 5
        X = np.arange(T * 3, dtype=np.float32).reshape(T, 3)
        out = tmp_path / "design.xmat.1D"
        _write_afni_xmat(
            X,
            str(out),
            n_stim_cols=1,
            condition_labels=["A"],
            run_starts=[0],
            tr=2.0,
            polort=1,
        )
        # Read back data rows (everything not starting with '#')
        lines = out.read_text().splitlines()
        data_lines = [ln for ln in lines if ln and not ln.startswith("#")]
        assert len(data_lines) == T
        reloaded = np.array([[float(v) for v in ln.split()] for ln in data_lines])
        np.testing.assert_allclose(reloaded, X, atol=1e-5)


