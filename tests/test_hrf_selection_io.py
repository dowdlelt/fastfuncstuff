"""
Tests for the I/O surface of design/hrf_selection.py:

- load_nuisance_file — multi-format parsing of motion/physio files
- _write_afni_xmat — AFNI xmat.1D writer with labelled columns
- load_hrf_selection_for_arma — round-trip with torch.save

The per-voxel HRF pipeline is a CLAUDE.md principle. These utilities
are the joints between voxel-wise HRF selection and downstream
analyses; bugs here corrupt the design matrix or the reuse path.
"""

