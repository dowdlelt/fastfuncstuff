"""IM REML benchmark: 3dREMLfit (via REML_cmd) vs ffs_reml (ARMA)."""

from __future__ import annotations

from pathlib import Path

from ..runner import BenchmarkContext, run_timed
from ..validation import compare_im_bucket

name = "glm_im_reml"
description = "IM model REML (3dREMLfit vs ffs_reml -Rbuck)"

RUNS = [1, 2, 3, 4, 5]
STIM_LABELS = ["faces", "bodies", "objects", "scenes", "scrambled"]

# Thresholds relaxed vs OLS — REML estimation differs slightly between implementations
THRESHOLDS = {
    "min_r": 0.9,
    "temporal_min_median_r": 0.9,
}


# ── Path helpers ──────────────────────────────────────────────────────────────


def _afni_dir(ctx: BenchmarkContext) -> Path:
    return ctx.data_dir / "afni_glm_IM"


def _ffs_dir(ctx: BenchmarkContext) -> Path:
    return ctx.data_dir / "ffs_glm_IM_REML"


def _scaled_input(ctx: BenchmarkContext, run: int) -> Path:
    return ctx.processing_dir / f"scaled_afni_mni_task-localizer_run-{run}.nii.gz"


def _automask_path(ctx: BenchmarkContext) -> Path:
    return ctx.processing_dir / "MNI_automask.nii.gz"


def _reml_cmd(ctx: BenchmarkContext) -> Path:
    """REML_cmd script generated by 3dDeconvolve (lives in afni_glm_IM)."""
    return _afni_dir(ctx) / "IM_afni_stats_localizer.REML_cmd"


def _afni_bucket(ctx: BenchmarkContext) -> Path:
    """AFNI REMLfit output bucket (generated by REML_cmd). Data is MNI-warped so AFNI uses +tlrc."""
    return _afni_dir(ctx) / "IM_afni_stats_localizer_REML+tlrc.HEAD"


def _ffs_bucket(ctx: BenchmarkContext) -> Path:
    return _ffs_dir(ctx) / "IM_ffs_stats_REML.nii.gz"


def _ffs_var(ctx: BenchmarkContext) -> Path:
    return _ffs_dir(ctx) / "IM_ffs_stats_REML_var.nii.gz"


def _xmat(ctx: BenchmarkContext) -> Path:
    """Design matrix written by glm_im (must run first)."""
    return _afni_dir(ctx) / "IM_X.xmat.1D"


# ── Stage interface ───────────────────────────────────────────────────────────


def check_prerequisites(ctx: BenchmarkContext) -> list[str]:
    missing = []
    if ctx.validate_only:
        for p in [_afni_bucket(ctx), _ffs_bucket(ctx)]:
            if not p.exists():
                missing.append(str(p))
    else:
        # Need the REML_cmd script that 3dDeconvolve (glm_im) wrote
        if not _reml_cmd(ctx).exists():
            missing.append(str(_reml_cmd(ctx)))
        # Need the xmat for ffs_reml
        if not _xmat(ctx).exists():
            missing.append(str(_xmat(ctx)))
        for run in RUNS:
            src = _scaled_input(ctx, run)
            if not src.exists():
                missing.append(str(src))
        if not _automask_path(ctx).exists():
            missing.append(str(_automask_path(ctx)))
    return missing


def run_ref(ctx: BenchmarkContext) -> float:
    """Run 3dREMLfit via the REML_cmd script generated by 3dDeconvolve."""
    afni = _afni_dir(ctx)

    if _afni_bucket(ctx).exists() and not ctx.force_ref:
        return 0.0

    elapsed, _ = run_timed(
        f"tcsh {_reml_cmd(ctx)} -overwrite -nofdr",
        label="3dREMLfit IM",
        cwd=afni,
    )
    return elapsed


def run_ffs(ctx: BenchmarkContext) -> float:
    """Run ffs_reml REML using the IM design matrix."""
    ffs = _ffs_dir(ctx)
    ffs.mkdir(parents=True, exist_ok=True)

    if _ffs_bucket(ctx).exists() and not ctx.force_ffs:
        return 0.0

    inputs = " ".join(str(_scaled_input(ctx, r)) for r in RUNS)
    mask = _automask_path(ctx)

    elapsed, _ = run_timed(
        f"ffs_reml "
        f"-input {inputs} "
        f"-matrix {_xmat(ctx)} "
        f"-Rbuck {_ffs_bucket(ctx)} "
        f"-Rvar {_ffs_var(ctx)} "
        f"-mask {mask} "
        f"-tout"
        f"{ctx.ffs_device_flag()}",
        label="ffs_reml IM REML",
        cwd=ffs,
    )
    return elapsed


def validate(ctx: BenchmarkContext) -> dict:
    """Compare AFNI REMLfit and FFS REML IM bucket files."""
    mask_path = _automask_path(ctx) if _automask_path(ctx).exists() else None

    result = compare_im_bucket(
        _afni_bucket(ctx),
        _ffs_bucket(ctx),
        mask_path=mask_path,
    )

    fstat_r      = result["fstat"]["r"]
    beta_min_r   = result["betas"]["min_r"]
    beta_temp_r  = result["betas"]["temporal_median_r"]
    tstat_min_r  = result["tstats"]["min_r"]
    tstat_temp_r = result["tstats"]["temporal_median_r"]

    passed = (
        fstat_r      >= THRESHOLDS["min_r"]
        and beta_min_r   >= THRESHOLDS["min_r"]
        and beta_temp_r  >= THRESHOLDS["temporal_min_median_r"]
        and tstat_min_r  >= THRESHOLDS["min_r"]
        and tstat_temp_r >= THRESHOLDS["temporal_min_median_r"]
    )

    summary = (
        f"F_r={fstat_r:.3f} "
        f"beta min_r={beta_min_r:.3f} temp_r={beta_temp_r:.3f} "
        f"tstat min_r={tstat_min_r:.3f} temp_r={tstat_temp_r:.3f} "
        f"(thresholds relaxed to {THRESHOLDS['min_r']})"
    )

    return {
        "passed": passed,
        "summary": summary,
        **result,
    }
