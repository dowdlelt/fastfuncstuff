"""IM REML benchmark: 3dREMLfit (via REML_cmd) vs ffs_reml (ARMA)."""

from __future__ import annotations

from pathlib import Path

from ..runner import BenchmarkContext, run_timed
from ..validation import compare_im_bucket

name = "glm_im_reml"
description = "IM model REML (3dREMLfit vs ffs_reml -Rbuck)"

_DEFAULT_STIM_LABELS = ["faces", "bodies", "objects", "scenes", "scrambled"]

# Thresholds relaxed vs OLS — REML estimation differs slightly between implementations.
#
# The omnibus F is NOT gated at parity. For an IM design (here ~600 single-trial
# regressors) the full-model F is a 600-dimensional quadratic form on a
# near-degenerate ARMA(1,1) covariance — the single most sensitive quantity in
# the bucket, amplifying sub-percent whitening differences that don't affect the
# scientific outputs. Those differences are real and unavoidable: AFNI fits the
# noise model in float64, while the (a,b) grid search runs float32 on GPU, so the
# per-voxel optimum wanders slightly along the flat a≈b ridge (CPU≈0.90, CUDA≈0.84
# against AFNI). Betas (≈0.995) and t-stats (≈0.98) — what people actually use —
# are excellent, so we gate on those and keep F as a reported diagnostic with a
# loose floor that still catches catastrophic breakage (e.g. the global-argmin
# regression that scored ≈0.70).
THRESHOLDS = {
    "min_r": 0.9,
    "temporal_min_median_r": 0.9,
    "fstat_floor_r": 0.75,
}


# ── Config helpers ────────────────────────────────────────────────────────────


def _glm_params(ctx: BenchmarkContext) -> dict:
    return ctx.get_stage_params("glm")


def _primary_task(ctx: BenchmarkContext) -> str:
    return _glm_params(ctx).get("primary_task", "localizer")


def _runs(ctx: BenchmarkContext) -> list[int]:
    return ctx.runs_for_task(_primary_task(ctx))


# ── Path helpers ──────────────────────────────────────────────────────────────


def _afni_dir(ctx: BenchmarkContext) -> Path:
    return ctx.data_dir / "afni_glm_IM"


def _ffs_dir(ctx: BenchmarkContext) -> Path:
    return ctx.data_dir / f"ffs_glm_IM_REML{ctx.ffs_tag}"


def _scaled_input(ctx: BenchmarkContext, run: int) -> Path:
    task = _primary_task(ctx)
    return ctx.processing_dir / f"scaled_afni_mni_task-{task}_run-{run}.nii.gz"


def _automask_path(ctx: BenchmarkContext) -> Path:
    return ctx.processing_dir / "MNI_automask.nii.gz"


def _reml_cmd(ctx: BenchmarkContext) -> Path:
    """REML_cmd script generated by 3dDeconvolve (lives in afni_glm_IM)."""
    task = _primary_task(ctx)
    return _afni_dir(ctx) / f"IM_afni_stats_{task}.REML_cmd"


def _afni_bucket(ctx: BenchmarkContext) -> Path:
    """AFNI REMLfit output bucket (generated by REML_cmd). Data is MNI-warped so AFNI uses +tlrc."""
    task = _primary_task(ctx)
    return _afni_dir(ctx) / f"IM_afni_stats_{task}_REML+tlrc.HEAD"


def _ffs_bucket(ctx: BenchmarkContext) -> Path:
    return _ffs_dir(ctx) / "IM_ffs_stats_REML.nii.gz"


def _ffs_var(ctx: BenchmarkContext) -> Path:
    return _ffs_dir(ctx) / "IM_ffs_stats_REML_var.nii.gz"


def _xmat(ctx: BenchmarkContext) -> Path:
    """Design matrix written by glm_im (must run first)."""
    return _afni_dir(ctx) / "IM_X.xmat.1D"


# ── Stage interface ───────────────────────────────────────────────────────────


def check_prerequisites(ctx: BenchmarkContext) -> list[str]:
    missing = []
    if ctx.validate_only:
        for p in [_afni_bucket(ctx), _ffs_bucket(ctx)]:
            if not p.exists():
                missing.append(str(p))
    else:
        # Need the REML_cmd script that 3dDeconvolve (glm_im) wrote
        if not _reml_cmd(ctx).exists():
            missing.append(str(_reml_cmd(ctx)))
        # Need the xmat for ffs_reml
        if not _xmat(ctx).exists():
            missing.append(str(_xmat(ctx)))
        for run in _runs(ctx):
            src = _scaled_input(ctx, run)
            if not src.exists():
                missing.append(str(src))
        # MNI_automask.nii.gz is only needed by run_ffs; created on demand there.
    return missing


def run_ref(ctx: BenchmarkContext) -> float:
    """Run 3dREMLfit via the REML_cmd script generated by 3dDeconvolve."""
    afni = _afni_dir(ctx)

    if _afni_bucket(ctx).exists() and not ctx.force_ref:
        return 0.0

    elapsed, _ = run_timed(
        f"tcsh {_reml_cmd(ctx)} -overwrite -nofdr",
        label="3dREMLfit IM",
        cwd=afni,
    )
    return elapsed


def run_ffs(ctx: BenchmarkContext) -> float:
    """Run ffs_reml REML using the IM design matrix."""
    ffs = _ffs_dir(ctx)
    ffs.mkdir(parents=True, exist_ok=True)

    # Ensure mask exists (may not if glm_im ran ref-only on this machine)
    mask_path = _automask_path(ctx)
    if not mask_path.exists():
        run_timed(
            f"3dAutomask -overwrite -prefix {mask_path} {_scaled_input(ctx, 1)}",
            label="3dAutomask MNI (glm_im_reml)",
            cwd=ctx.processing_dir,
        )

    if _ffs_bucket(ctx).exists() and not ctx.force_ffs:
        return 0.0

    inputs = " ".join(str(_scaled_input(ctx, r)) for r in _runs(ctx))
    mask = _automask_path(ctx)

    elapsed, _ = run_timed(
        f"ffs_reml "
        f"-input {inputs} "
        f"-matrix {_xmat(ctx)} "
        f"-Rbuck {_ffs_bucket(ctx)} "
        f"-Rvar {_ffs_var(ctx)} "
        f"-mask {mask} "
        f"-tout"
        f"{ctx.ffs_afni_mode_flag()}{ctx.ffs_device_flag()}",
        label="ffs_reml IM REML",
        cwd=ffs,
    )
    return elapsed


def validate(ctx: BenchmarkContext) -> dict:
    """Compare AFNI REMLfit and FFS REML IM bucket files."""
    mask_path = _automask_path(ctx) if _automask_path(ctx).exists() else None

    result = compare_im_bucket(
        _afni_bucket(ctx),
        _ffs_bucket(ctx),
        mask_path=mask_path,
    )

    fstat_r = result["fstat"]["r"]
    beta_min_r = result["betas"]["min_r"]
    beta_temp_r = result["betas"]["temporal_median_r"]
    tstat_min_r = result["tstats"]["min_r"]
    tstat_temp_r = result["tstats"]["temporal_median_r"]

    # Gate on betas + t-stats (the scientific outputs); F is a diagnostic with a
    # loose floor only (see THRESHOLDS rationale above).
    passed = (
        beta_min_r >= THRESHOLDS["min_r"]
        and beta_temp_r >= THRESHOLDS["temporal_min_median_r"]
        and tstat_min_r >= THRESHOLDS["min_r"]
        and tstat_temp_r >= THRESHOLDS["temporal_min_median_r"]
        and fstat_r >= THRESHOLDS["fstat_floor_r"]
    )

    summary = (
        f"F_r={fstat_r:.3f} (diagnostic, floor {THRESHOLDS['fstat_floor_r']}) "
        f"beta min_r={beta_min_r:.3f} temp_r={beta_temp_r:.3f} "
        f"tstat min_r={tstat_min_r:.3f} temp_r={tstat_temp_r:.3f} "
        f"(gate {THRESHOLDS['min_r']})"
    )

    return {
        "passed": passed,
        "summary": summary,
        **result,
    }
